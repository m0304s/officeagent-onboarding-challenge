r"""파서들이 공유하는 텍스트 정규화.

파서마다 따로 두면 한쪽만 고쳐졌을 때 "같은 문서인데 포맷에 따라 다르게 잘린다"가 된다.
"""


def normalize_newlines(text: str) -> str:
    r"""`\r\n` · `\r` 를 `\n` 으로 통일한다.

    청커의 구분자 우선순위가 `\n\n` → `\n` 이라, 윈도우에서 만든 문서를 그대로 두면
    문단 경계가 `\r\n\r\n` 이 되어 최우선 구분자에 걸리지 않는다. 그러면 같은 내용의
    문서가 만들어진 운영체제에 따라 다르게 잘린다.

    정규화한 텍스트가 곧 세그먼트 본문이므로 청크의 오프셋도 이 텍스트 기준이다 —
    "청크 본문은 추출된 원문의 부분 문자열"이라는 계약은 그대로 성립한다.
    """
    return text.replace("\r\n", "\n").replace("\r", "\n")
